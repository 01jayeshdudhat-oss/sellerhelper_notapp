def _validated_session_cookie_domain(configured_domain, allowed_hosts):
    if not configured_domain:
        return None

    domain = configured_domain.strip().lower().lstrip(".").rstrip(".")
    if not domain or domain == "*":
        return None
    try:
        ipaddress.ip_address(domain)
    except ValueError:
        pass
    else:
        return None

    matching_hosts = (
        host.strip().lower().lstrip(".").rstrip(".")
        for host in allowed_hosts
        if host.strip() and host.strip() != "*"
    )
    if any(
        host == domain or host.endswith(f".{domain}")
        for host in matching_hosts
    ):
        return configured_domain.strip()

    warnings.warn(
        "SESSION_COOKIE_DOMAIN does not match any configured ALLOWED_HOSTS entry; "
        "using host-only session cookies.",
        RuntimeWarning,
        stacklevel=2,
    )
    return None


# Keep sessions host-only by default so local-IP/mobile deployments can log in.
# A valid parent domain may be set when storefront subdomains must share sessions.
